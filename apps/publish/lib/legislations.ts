export const LEGISLATIONS: Legislation[] = RAW.map((title) => ({
  id: title
    .toLowerCase()
    .replace(/['’]/g, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, ""),
  slug: title
    .toLowerCase()
    .replace(/['’]/g, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, ""),
  title,
  price: 500,
}))

export function getLegislationBySlug(slug: string): Legislation | undefined {
  return LEGISLATIONS.find((l) => l.slug === slug)
}

export function getLegislationsByLetter(
  letter: string,
): Legislation[] {
  return LEGISLATIONS.filter((l) =>
    l.title.toUpperCase().startsWith(letter),
  )
}

export const ALPHABET = "ABCDEFGHIJKLMNOPQRSTUVWXYZ".split("")

export function getLettersWithContent(): string[] {
  const available = new Set(
    LEGISLATIONS.map((l) => l.title[0]?.toUpperCase()).filter(Boolean),
  )
  return ALPHABET.filter((l) => available.has(l))
}
