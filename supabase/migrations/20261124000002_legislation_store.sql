-- Legislation store: the catalogue, the file, and who owns a copy.
--
-- Before this the shop rendered a price and a title from a static list and
-- delivered a placeholder <a href="#">Download PDF</a> — money in, nothing out.
-- A legislation is only purchasable once its file exists, and the file is served
-- through a signed URL after the buyer's transaction is verified.

create table if not exists public.legislations (
  slug text primary key,
  title text not null,
  price integer not null default 500 check (price >= 0),
  file_path text,
  page_count integer,
  updated_at timestamptz not null default now()
);

alter table public.legislations enable row level security;

-- Catalogue metadata is public; the file path is useless without a signed URL.
drop policy if exists "Legislation catalogue is public" on public.legislations;
create policy "Legislation catalogue is public"
  on public.legislations for select
  using (true);

-- Purchases are matched against transactions.metadata.items[].id
create index if not exists transactions_shop_idx
  on public.transactions (user_id, status)
  where plan_role = 'legislation_buyer';

-- Private bucket: downloads are signed per request, never public.
insert into storage.buckets (id, name, public)
values ('legislations', 'legislations', false)
on conflict (id) do nothing;

